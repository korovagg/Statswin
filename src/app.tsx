import { useCallback, useEffect, useMemo, useRef, useState } from "react";
import styles from "./css/app.module.scss";
import FilterBar from "./components/FilterBar";
import { PeriodType, PeriodRange } from "./types/period";
import { StatsChart } from "./components/StatsChart";
import { StatsSummary } from "./components/StatsSummary";
import { StatsExtraRow } from "./components/StatsExtraRow";
import { TopTracks } from "./components/TopTracks";
import { TopArtists } from "./components/TopArtists";
import { SettingsModal } from "./components/SettingsModal";
import { InfoModal } from "./components/InfoModal";
import { AppIcon, InfoIcon, SettingsIcon } from "./components/icons";
import { getDefaultRangeForPeriod } from "./utils/dateRanges";
import {
  getSessionsInRange,
  getTotalMsInRange,
  migrateV2ToV3,
  flushStorage,
} from "./utils/storage";
import { getListeningTracker } from "./services/listeningTracker";
import { getAppVersion } from "./version";
import { I18nProvider, useI18n } from "./utils/i18n";
import {
  getChartSeries,
  getChartTitleKey,
  getPreviousPeriodLabelKey,
  resolvePeriodRange,
  resolvePreviousRange,
} from "./utils/periods";
import { CheckLimitsBanner } from "./components/StorageBanner";

/**
 * Statswin CustomApp root with a single `I18nProvider`.
 *
 * The mount code generated by `spicetify-creator` does
 * `const render = () => statswin.default(); Spicetify.ReactDOM.render(render())`,
 * so a component element is what gets mounted.
 */
export default function App() {
  return (
    <I18nProvider>
      <AppView />
    </I18nProvider>
  );
}

/**
 * Finds the element that actually scrolls for `node`.
 *
 * Spotify's main view is not the document scroller: content lives in an inner
 * container, so a plain `window.scroll` listener would never fire.
 */
function findScrollParent(node: HTMLElement): HTMLElement | null {
  let current: HTMLElement | null = node.parentElement;
  while (current) {
    const style = window.getComputedStyle(current);
    const overflowY = style.overflowY;
    const scrollable = overflowY === "auto" || overflowY === "scroll" || overflowY === "overlay";
    if (scrollable && current.scrollHeight > current.clientHeight) return current;
    current = current.parentElement;
  }
  return document.scrollingElement instanceof HTMLElement ? document.scrollingElement : null;
}

function AppView() {
  const { t, lang } = useI18n();
  const [period, setPeriod] = useState<PeriodType>(PeriodType.Today);
  const [customRange, setCustomRange] = useState<PeriodRange>(() => getDefaultRangeForPeriod(PeriodType.Today));
  const [refreshTick, setRefreshTick] = useState(0);
  const [liveMs, setLiveMs] = useState(0);
  const [settingsOpen, setSettingsOpen] = useState(false);
  const [infoOpen, setInfoOpen] = useState(false);
  const [headerStuck, setHeaderStuck] = useState(false);
  const headerRef = useRef<HTMLElement | null>(null);

  const range = useMemo(() => resolvePeriodRange(period, customRange), [period, customRange]);

  // `refreshTick` deliberately participates: the store is mutable in memory and
  // React cannot observe it, so tracker events bump the tick to re-read.
  const rangeSessions = useMemo(
    () => getSessionsInRange(range.start, range.end),
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [range.start, range.end, refreshTick]
  );

  const storedTotalMs = useMemo(
    () => getTotalMsInRange(range.start, range.end),
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [range.start, range.end, refreshTick]
  );

  const previousRange = useMemo(() => resolvePreviousRange(period, range), [period, range]);
  const previousTotalMs = useMemo(
    () => getTotalMsInRange(previousRange.start, previousRange.end),
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [previousRange.start, previousRange.end, refreshTick]
  );

  const chartSeries = useMemo(
    () => getChartSeries(period, range, lang),
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [period, range.start, range.end, lang, refreshTick]
  );

  const chartTitleKey = useMemo(() => getChartTitleKey(period, range), [period, range]);

  const topRange = useMemo(() => {
    if (period === PeriodType.Today || period === PeriodType.Yesterday) {
      return getDefaultRangeForPeriod(period);
    }
    return range;
  }, [period, range]);

  const topSessions = useMemo(
    () => getSessionsInRange(topRange.start, topRange.end),
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [topRange.start, topRange.end, refreshTick]
  );

  // The sticky header gains its separator shadow only once content scrolls
  // underneath it, which keeps the resting page flat.
  useEffect(() => {
    const container = headerRef.current?.parentElement;
    if (!container) return;
    const scroller = findScrollParent(container);
    // `document.scrollingElement` (the <html> element) is the page scroller;
    // its own bounding rect moves with the scroll, so the boundary must be 0.
    const isPageScroller = !scroller || scroller === document.scrollingElement;
    const update = () => {
      const headerTop = headerRef.current?.getBoundingClientRect().top ?? 0;
      const boundary = isPageScroller ? 0 : scroller.getBoundingClientRect().top;
      const scrolled = isPageScroller ? window.scrollY : scroller.scrollTop;
      setHeaderStuck(headerTop <= boundary + 1 && scrolled > 0);
    };
    // Window scroll events are not captured by listeners on the document
    // element in every webview, so the page scroller listens on `window`.
    const target: HTMLElement | Window = isPageScroller ? window : scroller;
    target.addEventListener("scroll", update, { passive: true });
    window.addEventListener("resize", update);
    update();
    return () => {
      target.removeEventListener("scroll", update);
      window.removeEventListener("resize", update);
    };
  }, []);

  useEffect(() => {
    // Run the v2-to-v3 migration before anything reads storage, then refresh.
    migrateV2ToV3();
    const tracker = getListeningTracker();
    if (!tracker.isRunning()) tracker.start();

    const refresh = () => setRefreshTick((value) => value + 1);
    const onTick = (event: Event) => {
      const detail = (event as CustomEvent<{ liveMs?: number }>).detail;
      setLiveMs(detail?.liveMs ?? tracker.getLiveAccrualMs());
    };
    const onVisibility = () => {
      if (document.visibilityState === "visible") refresh();
    };
    const onUnload = () => flushStorage();

    window.addEventListener("statswin:session-added", refresh);
    window.addEventListener("statswin:tick", onTick);
    window.addEventListener("statswin:storage-warning", refresh);
    document.addEventListener("visibilitychange", onVisibility);
    window.addEventListener("pagehide", onUnload);
    refresh();
    setLiveMs(tracker.getLiveAccrualMs());

    return () => {
      window.removeEventListener("statswin:session-added", refresh);
      window.removeEventListener("statswin:tick", onTick);
      window.removeEventListener("statswin:storage-warning", refresh);
      document.removeEventListener("visibilitychange", onVisibility);
      window.removeEventListener("pagehide", onUnload);
      // The tracker keeps running: the extension owns its lifecycle.
    };
  }, []);

  const totalMs = storedTotalMs + (period === PeriodType.Today ? liveMs : 0);

  const handlePeriodChange = useCallback((next: PeriodType) => {
    setPeriod(next);
    if (next === PeriodType.Custom) {
      // Entering Custom keeps the previous selection; only create a sane default
      // when the stored range is degenerate.
      setCustomRange((current) =>
        current.start === current.end ? getDefaultRangeForPeriod(PeriodType.Today) : current
      );
    }
  }, []);

  const previousPeriodLabel = t(getPreviousPeriodLabelKey(period));

  return (
    <div className={styles.container}>
      <header
        ref={headerRef}
        className={`${styles.topBar} ${styles.topBarSticky}`}
        data-stuck={headerStuck ? "true" : "false"}
      >
        <div className={styles.brand}>
          <span className={styles.brandMark} aria-hidden>
            <AppIcon />
          </span>
          <span className={styles.brandText}>
            <span className={styles.brandName}>Statswin</span>
            <span className={styles.brandVersion}>v{getAppVersion()}</span>
          </span>
        </div>

        <FilterBar
          period={period}
          onPeriodChange={handlePeriodChange}
          customRange={customRange}
          onCustomRangeChange={setCustomRange}
        />

        <div className={styles.topActions}>
          <button
            type="button"
            className={styles.iconButton}
            aria-label={t("filter.info")}
            aria-haspopup="dialog"
            aria-controls="statswin-info-modal"
            onClick={() => setInfoOpen(true)}
          >
            <InfoIcon />
          </button>
          <button
            type="button"
            className={styles.iconButton}
            aria-label={t("filter.settings")}
            aria-haspopup="dialog"
            aria-controls="statswin-settings-modal"
            onClick={() => setSettingsOpen(true)}
          >
            <SettingsIcon />
          </button>
        </div>
      </header>

      <CheckLimitsBanner />

      <main className={styles.main}>
        <StatsSummary
          className={styles.heroSection}
          range={range}
          totalMs={totalMs}
          previousMs={previousTotalMs}
          previousLabel={previousPeriodLabel}
        />

        <div className={styles.chartSection}>
          <StatsChart data={chartSeries.points} titleKey={chartTitleKey} />
        </div>

        <section className={styles.extraStatsSection}>
          <StatsExtraRow sessions={rangeSessions} rangeStart={range.start} />
        </section>

        <TopTracks sessions={topSessions} topRange={topRange} />
        <TopArtists sessions={topSessions} topRange={topRange} />
      </main>

      <SettingsModal open={settingsOpen} onClose={() => setSettingsOpen(false)} />
      <InfoModal open={infoOpen} onClose={() => setInfoOpen(false)} />
    </div>
  );
}
